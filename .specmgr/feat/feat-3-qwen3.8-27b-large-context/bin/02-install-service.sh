#!/usr/bin/env bash
# feat-3-qwen3.8-27b-large-context — install the PRODUCTION systemd
# service (NVFP4 weights, 896K context via YaRN factor 3.5, MTP
# speculative decoding, FP8 KV cache) on a NEW system.
#
# Run 01-build.sh FIRST (installs vLLM + downloads/pins the NVFP4
# checkpoint). This script only deploys the launch script + systemd
# --user unit and does NOT start the service by default -- this
# matches the feature's "systemd-only, never auto-start at boot"
# policy (README REQ-009): the unit is installed `disabled` (no
# `systemctl --user enable`), so it survives logout (via lingering)
# without launching automatically at boot. Pass --start to start it
# immediately after install.
#
# HARDWARE ASSUMPTION: this deploys the config validated on a GB10-class
# box (~120 GB unified CPU+GPU memory pool). If your target box has a
# meaningfully different amount of VRAM/unified memory, the
# --kv-cache-memory-bytes value below (33 GiB) and/or --max-model-len
# (917504) may need re-deriving via the same capacity-step-up
# methodology described in the feature README (Task 2.1-2.3/6.2 step 4)
# rather than assumed to transfer as-is.
#
# GPU COUNT: this deploys single-GPU (--tensor-parallel-size 1) by
# default, matching the GB10 this feature was validated on (it only has
# ONE GPU -- a single Grace-Blackwell SoC with one unified memory pool,
# nothing to span). Set TP to a value > 1 ONLY if your target box has
# multiple GPUs and you deliberately want to shard across them --
# this is UNVALIDATED by this feature: KV-cache capacity/headroom
# (Task 2.1-2.3/6.2 step 4) and the MTP throughput measurement
# (Task 6.3) were both measured at TP=1 only. Re-run the same
# capacity-step-up methodology before trusting the 896K context /
# --kv-cache-memory-bytes value at TP>1.
#
# Env vars (must match what 01-build.sh used, if you overrode them):
#   VENV_DIR    (default: $HOME/venvs/vllm)
#   MODEL_DIR   (default: $HOME/models/qwen3.8-27b-nvfp4)
#   SCRIPTS_DIR (default: $HOME/scripts)
#   TP          tensor-parallel-size / GPU count (default: 1)
set -euo pipefail

VENV_DIR="${VENV_DIR:-$HOME/venvs/vllm}"
MODEL_DIR="${MODEL_DIR:-$HOME/models/qwen3.8-27b-nvfp4}"
SCRIPTS_DIR="${SCRIPTS_DIR:-$HOME/scripts}"
SYSTEMD_USER_DIR="$HOME/.config/systemd/user"
SERVICE_NAME="qwen3.8-27b-nvfp4-896k"
TP="${TP:-1}"
START_NOW=0

for arg in "$@"; do
  case "$arg" in
    --start) START_NOW=1 ;;
    *) echo "Unknown argument: $arg (only --start is supported)" >&2; exit 1 ;;
  esac
done

echo "=== Pre-flight checks ==="
if [ ! -x "${VENV_DIR}/bin/vllm" ]; then
  echo "ERROR: ${VENV_DIR}/bin/vllm not found -- run 01-build.sh first." >&2
  exit 1
fi
if [ ! -f "${MODEL_DIR}/config.json" ]; then
  echo "ERROR: ${MODEL_DIR}/config.json not found -- run 01-build.sh first." >&2
  exit 1
fi
if ! [[ "${TP}" =~ ^[0-9]+$ ]] || [ "${TP}" -lt 1 ]; then
  echo "ERROR: TP must be a positive integer (got '${TP}')." >&2
  exit 1
fi
GPU_COUNT="$(nvidia-smi -L 2>/dev/null | wc -l)"
if [ "${TP}" -gt 1 ]; then
  echo "WARNING: TP=${TP} requested -- sharding across multiple GPUs is UNVALIDATED"
  echo "by this feature (896K context / --kv-cache-memory-bytes were only measured"
  echo "at TP=1 on a single-GPU GB10). Re-run the capacity-step-up methodology"
  echo "(README Task 2.1-2.3/6.2 step 4) at this TP before trusting the result."
  if [ -n "${GPU_COUNT}" ] && [ "${GPU_COUNT}" -lt "${TP}" ]; then
    echo "ERROR: TP=${TP} but only ${GPU_COUNT} GPU(s) visible via nvidia-smi." >&2
    exit 1
  fi
fi
PYHDR="$(find "$HOME/.local/share/uv/python" -maxdepth 4 -path '*cpython-3.12*/include/python3.12/Python.h' 2>/dev/null | head -1)"
if [ -z "${PYHDR}" ]; then
  echo "ERROR: could not find the uv-installed CPython 3.12 headers -- run 01-build.sh first." >&2
  exit 1
fi
CPATH_DIR="$(dirname "${PYHDR}")"
echo "vLLM venv:  ${VENV_DIR}"
echo "Model dir:  ${MODEL_DIR}"
echo "Headers:    ${CPATH_DIR}"
echo "GPU count:  ${GPU_COUNT:-unknown} visible, TP=${TP} requested"
echo

mkdir -p "${SCRIPTS_DIR}" "${SYSTEMD_USER_DIR}"

echo "=== Writing launch script: ${SCRIPTS_DIR}/${SERVICE_NAME}.sh ==="
cat > "${SCRIPTS_DIR}/${SERVICE_NAME}.sh" <<SCRIPT_EOF
#!/usr/bin/env bash
# Production launch script for Qwen3.8-27B-NVFP4 + YaRN at 896K
# (917,504-token) context, YaRN factor 3.5, NVFP4 weights, FP8 KV cache,
# WITH MTP speculative decoding.
#
# Generated by .specmgr/feat/feat-3-qwen3.8-27b-large-context/bin/02-install-service.sh
# (TP=${TP}) -- see that feature's README (Phase 6, Tasks 6.2/6.3) for
# the full validation record (capacity/headroom measurements,
# correctness checks, and the 2.66x/3.12x MTP throughput measurement)
# behind every flag below. Re-run the install script to regenerate this
# file if the feature's chosen production config ever changes; do not
# hand-edit without re-running the same validation methodology.
#
# NOTE: --tensor-parallel-size ${TP} was requested at install time.$([ "${TP}" -gt 1 ] && echo " This is
# UNVALIDATED by this feature -- 896K context / --kv-cache-memory-bytes
# were only measured at TP=1 on a single-GPU GB10 (see README Task
# 2.1-2.3/6.2 step 4). Re-run that capacity-step-up methodology at this
# TP before trusting this config in production.")
set -euo pipefail

export CPATH="${CPATH_DIR}"
export PATH="${VENV_DIR}/bin:\$PATH"
export VLLM_ALLOW_LONG_MAX_MODEL_LEN=1
export VLLM_ENGINE_READY_TIMEOUT_S=3600
export VLLM_DISABLE_COMPILE_CACHE=1

# factor = 917504 / 262144 = 3.5
HF_OVERRIDES='{"text_config": {"rope_parameters": {"mrope_interleaved": true, "mrope_section": [11, 11, 10], "rope_type": "yarn", "rope_theta": 10000000, "partial_rotary_factor": 0.25, "factor": 3.5, "original_max_position_embeddings": 262144}}}'

exec "${VENV_DIR}/bin/vllm" serve "${MODEL_DIR}" \\
  --port 8000 --trust-remote-code --no-enable-prefix-caching \\
  --tensor-parallel-size ${TP} \\
  --max-model-len 917504 \\
  --served-model-name qwen3.8:27b-nvfp4-896k \\
  --kv-cache-dtype fp8 \\
  --kv-cache-memory-bytes 35433480192 \\
  --hf-overrides "\${HF_OVERRIDES}" \\
  --speculative-config '{"method":"mtp","num_speculative_tokens":5}' \\
  --enable-auto-tool-choice --tool-call-parser qwen3_xml --reasoning-parser qwen3
SCRIPT_EOF
chmod +x "${SCRIPTS_DIR}/${SERVICE_NAME}.sh"

echo "=== Writing systemd unit: ${SYSTEMD_USER_DIR}/${SERVICE_NAME}.service ==="
cat > "${SYSTEMD_USER_DIR}/${SERVICE_NAME}.service" <<UNIT_EOF
[Unit]
Description=vLLM - Qwen3.8-27B-NVFP4 (896K context, YaRN factor 3.5, NVFP4 weights, FP8 KV cache, MTP speculative decoding) -- feat-3-qwen3.8-27b-large-context production
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory=%h
ExecStart=${SCRIPTS_DIR}/${SERVICE_NAME}.sh
Restart=on-failure
RestartSec=10
# Weight load + KV-cache profiling/compile at long max-model-len is
# slow; give systemd a longer leash than the launch script's own
# internal VLLM_ENGINE_READY_TIMEOUT_S=3600 so systemd never kills the
# unit mid-startup.
TimeoutStartSec=4200
LimitNOFILE=1048576

[Install]
WantedBy=default.target
UNIT_EOF

echo "=== Enabling lingering (survive logout without autostart at boot) ==="
if loginctl show-user "$(whoami)" 2>/dev/null | grep -q '^Linger=yes'; then
  echo "Lingering already enabled for $(whoami)."
else
  loginctl enable-linger "$(whoami)" \
    || echo "WARNING: could not enable lingering (may need polkit permission for your own user, or root) -- the service will still work while you stay logged in."
fi

echo "=== systemctl --user daemon-reload ==="
systemctl --user daemon-reload

echo
echo "Installed: ${SERVICE_NAME}.service"
echo "Deliberately left 'disabled' (will NOT autostart at boot, per REQ-009's policy)."
systemctl --user status "${SERVICE_NAME}.service" --no-pager || true

if [ "${START_NOW}" -eq 1 ]; then
  echo
  echo "=== --start given: starting the service now ==="
  systemctl --user start "${SERVICE_NAME}.service"
  echo "Started. Cold load typically takes ~4-9 minutes on GB10-class hardware"
  echo "(weight load without page-cache prefetch + KV-cache profiling/compile)."
  echo "Check readiness with: curl http://localhost:8000/health"
else
  echo
  echo "Not started (default). Start it explicitly with:"
  echo "  systemctl --user start ${SERVICE_NAME}.service"
  echo "Then verify with:"
  echo "  curl http://localhost:8000/v1/models"
  echo "  curl http://localhost:8000/v1/chat/completions -H 'Content-Type: application/json' -d '{\"model\":\"qwen3.8:27b-nvfp4-896k\",\"messages\":[{\"role\":\"user\",\"content\":\"hi\"}],\"max_tokens\":10}'"
fi
